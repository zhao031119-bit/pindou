import fs from 'node:fs';
import path from 'node:path';

const SOURCE_URL = 'https://git.xiongxiao.me/abearxiong/get-colors-from-beans/raw/branch/main/colorMap.json';

const TARGETS = {
  mard: { title: 'Mard-291', name: 'MARD家' },
  panpan: { title: '盼盼-289', name: '盼盼家' },
  common: { title: 'Mard-291', name: '通用' },
  coco: { title: 'COCO-291', name: 'COCO' },
  manman: { title: '漫漫-278', name: '漫漫家' },
  mixiaowo: { title: '咪小窝-290', name: '咪小窝' },
  xiaowu: { title: '小舞-291', name: '小舞家' },
  huangdoudou: { title: '黄豆豆-291', name: '黄豆豆' }
};

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Failed to fetch palette data: ${response.status}`);
}

const colorMap = await response.json();
const output = {};

for (const [paletteId, target] of Object.entries(TARGETS)) {
  output[paletteId] = [];
  for (const [hex, entries] of Object.entries(colorMap)) {
    const hits = entries.filter((entry) => entry['color-title'] === target.title);
    for (const hit of hits) {
      output[paletteId].push({
        code: String(hit['color-name']),
        name: `${target.name} ${hit['color-name']}`,
        hex: hit.color || hex
      });
    }
  }
  output[paletteId].sort((a, b) => a.code.localeCompare(b.code, 'zh-Hans-u-kn-true'));
}

const targetFile = path.join(process.cwd(), 'miniprogram', 'data', 'palette-data.js');
fs.mkdirSync(path.dirname(targetFile), { recursive: true });
fs.writeFileSync(
  targetFile,
  `// Generated by scripts/fetch-palettes.mjs\n` +
    `// Source: ${SOURCE_URL}\n` +
    `module.exports = ${JSON.stringify(output, null, 2)};\n`,
  'utf8'
);

for (const [id, colors] of Object.entries(output)) {
  console.log(`${id}: ${colors.length}`);
}
